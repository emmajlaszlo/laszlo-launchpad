const now = new Date().toISOString()

type SeedCompany = Omit<Company, 'createdAt' | 'lastChecked' | 'stage' | 'contacts'> & {
  contacts?: string
}

function company(c: SeedCompany): Company {
  return {
    ...c,
    contacts: c.contacts ?? '',
    stage: 'watching',
    lastChecked: null,
    createdAt: now,
  }
}

